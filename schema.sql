-- 1. Create dispatches table
CREATE TABLE IF NOT EXISTS public.dispatches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_date TEXT NOT NULL,
    order_no TEXT NOT NULL,
    customer TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Dispatched',
    remarks TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create indexes for high performance querying
CREATE INDEX IF NOT EXISTS idx_dispatches_date ON public.dispatches(dispatch_date);
CREATE INDEX IF NOT EXISTS idx_dispatches_order_no ON public.dispatches(order_no);

-- 2. Configure Row Level Security (RLS) for public/anon access
ALTER TABLE public.dispatches ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read access" ON public.dispatches;
CREATE POLICY "Allow public read access" ON public.dispatches FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow public insert access" ON public.dispatches;
CREATE POLICY "Allow public insert access" ON public.dispatches FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update access" ON public.dispatches;
CREATE POLICY "Allow public update access" ON public.dispatches FOR UPDATE USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete access" ON public.dispatches;
CREATE POLICY "Allow public delete access" ON public.dispatches FOR DELETE USING (true);

-- 3. Optional Settings & Remarks Table
CREATE TABLE IF NOT EXISTS public.settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category TEXT NOT NULL,
    value TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read access on settings" ON public.settings;
CREATE POLICY "Allow public read access on settings" ON public.settings FOR SELECT USING (true);
DROP POLICY IF EXISTS "Allow public write access on settings" ON public.settings;
CREATE POLICY "Allow public write access on settings" ON public.settings FOR ALL USING (true) WITH CHECK (true);

